import { spawn, execFileSync } from 'node:child_process';
import { mkdirSync, openSync, closeSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';
const root = process.cwd();
const proof = resolve(root, 'proof/audit/IW-UI-AUDIT/repair');
mkdirSync(proof, { recursive: true });
const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => key.toUpperCase() !== 'DATABASE_URL'));
const sources = ['package.json','package-lock.json','vite.config.ts','src/studio/Studio.tsx','src/studio/IsoCanvas.tsx','src/studio/DocumentPreview.tsx','src/studio/store.ts'];
const hash = path => createHash('sha256').update(readFileSync(resolve(root, path))).digest('hex');
const before = Object.fromEntries(sources.map(path=>[path,hash(path)]));
const log = openSync(resolve(proof, 'build01.log'), 'w');
const startedAt = new Date().toISOString();
const child = spawn(process.execPath, [resolve(dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js'), 'run', 'build'], { cwd:root, env, windowsHide:true, stdio:['ignore',log,log] });
const exitCode = await new Promise((done,reject)=>{child.once('error',reject);child.once('exit',done);});
closeSync(log);
const after = Object.fromEntries(sources.map(path=>[path,hash(path)]));
const record = {startedAt,completedAt:new Date().toISOString(),command:'npm run build',exitCode,databaseUrlRemovedFromChild:true,appEnvAllowsOnlyViteKeys:true,head:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),sourceBefore:before,sourceAfter:after,sourcesUnchanged:JSON.stringify(before)===JSON.stringify(after),concurrentAdditions:'New industry construction pure modules and tracker/handover files; source is not a clean HEAD checkout.'};
writeFileSync(resolve(proof,'build01.json'),JSON.stringify(record,null,2));
console.log(JSON.stringify(record,null,2));
process.exitCode = exitCode ?? 1;
