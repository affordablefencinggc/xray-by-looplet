import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const root = process.cwd();
const built = process.argv.includes('--built');
const output = resolve(root, 'screenshots/industry-baseline', built ? 'built' : '.');
const proof = resolve(root, 'proof/audit/IW-BASELINE');
await mkdir(output, { recursive: true });
await mkdir(proof, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const results = [];
try {
  for (const viewport of [{ name: 'desktop', width: 1280, height: 800 }, { name: 'mobile', width: 390, height: 844 }]) {
    const context = await browser.newContext({ viewport });
    const page = await context.newPage();
    const result = { viewport, consoleErrors: [], pageErrors: [], failedRequests: [], responses: [], steps: [] };
    page.on('pageerror', e => result.pageErrors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') result.consoleErrors.push(m.text()); });
    page.on('requestfailed', r => result.failedRequests.push({ url: r.url(), error: r.failure()?.errorText }));
    page.on('response', r => { if(r.status() >= 400) result.responses.push({ url: r.url(), status: r.status() }); });
    await page.goto(`http://127.0.0.1:${built ? 8081 : 8080}/`, { waitUntil: 'networkidle' });
    await page.getByText('Checking saved evidence and original files', { exact: true }).waitFor({ state: 'hidden', timeout: 15000 });
    await page.locator('[data-hydration-status="ready"]').waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Open plan' && !button.disabled));
    await page.screenshot({ path: resolve(output, `${viewport.name}-settled-before.png`), fullPage: true });
    result.steps.push({ name: 'settled-before', body: await page.locator('body').innerText(), inputs: await page.locator('input').evaluateAll(nodes => nodes.map(n=>({type:n.type,accept:n.accept}))) });
    const chooserPromise = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Open plan', exact: true }).first().click();
    await (await chooserPromise).setFiles(resolve(root, 'engine/fixtures/svg/sample-plan.svg'));
    await page.waitForTimeout(1500);
    await page.screenshot({ path: resolve(output, `${viewport.name}-import-after.png`), fullPage: true });
    result.steps.push({ name: 'actual-source-import', body: await page.locator('body').innerText() });
    await page.getByRole('button', { name: 'Measure', exact: true }).click();
    await page.waitForTimeout(400);
    await page.screenshot({ path: resolve(output, `${viewport.name}-measure-before.png`), fullPage: true });
    result.steps.push({ name: 'measure-before', body: await page.locator('body').innerText(), canvases: await page.locator('canvas').count() });
    await page.getByLabel('Known distance', { exact: true }).fill('12');
    await page.getByRole('button', { name: 'Pick two points', exact: true }).click();
    const canvas = page.locator('canvas').first();
    await canvas.scrollIntoViewIfNeeded();
    const box = await canvas.boundingBox();
    await canvas.click({ position: { x: box.width * 0.1, y: box.height * 0.25 } });
    await canvas.click({ position: { x: box.width * 0.8, y: box.height * 0.25 } });
    await page.getByRole('button', { name: 'Lock scale', exact: true }).click();
    await page.getByText('Scale is locked for measurements on this sheet.', { exact: true }).waitFor();
    await page.screenshot({ path: resolve(output, `${viewport.name}-calibration-after.png`), fullPage: true });
    result.steps.push({ name: 'actual-calibration-lock', proof: 'Real distance input, two canvas clicks, lock button; interaction proof only, not validated source geometry accuracy.' });
    await canvas.scrollIntoViewIfNeeded();
    await page.getByRole('button', { name: /^Run L$/ }).click();
    await canvas.click({ position: { x: box.width * 0.2, y: box.height * 0.45 } });
    await canvas.click({ position: { x: box.width * 0.7, y: box.height * 0.45 } });
    await page.getByRole('button', { name: 'Finish trace', exact: true }).click();
    await page.screenshot({ path: resolve(output, `${viewport.name}-trace-before-zoom.png`), fullPage: true });
    const source = page.locator('.measure-document-preview img').first();
    const sourceGeometry = () => source.evaluate(node => { const box=node.getBoundingClientRect(); const style=getComputedStyle(node); return { x:box.x, y:box.y, width:box.width, height:box.height, transform:style.transform, objectFit:style.objectFit, naturalWidth:node.naturalWidth, naturalHeight:node.naturalHeight }; });
    const beforeSourceGeometry = await sourceGeometry();
    const sourceHash = async () => createHash('sha256').update(await source.screenshot()).digest('hex');
    const beforeSource = await sourceHash();
    const beforeCanvas = await canvas.evaluate(node => node.toDataURL());
    await page.getByTitle('Zoom In', { exact: true }).click();
    await page.waitForTimeout(200);
    const afterSource = await sourceHash();
    const afterCanvas = await canvas.evaluate(node => node.toDataURL());
    await page.screenshot({ path: resolve(output, `${viewport.name}-zoom-after.png`), fullPage: true });
    result.steps.push({ name: 'actual-zoom', sourceGeometryUnchanged: JSON.stringify(beforeSourceGeometry) === JSON.stringify(await sourceGeometry()), beforeSourceGeometry, afterSourceGeometry: await sourceGeometry(), canvasPixelsChanged: beforeCanvas !== afterCanvas, compositedSourceCropNote: 'Crop includes overlay and controls; hashes are not isolated image pixel evidence.', beforeCompositedCropSha256: beforeSource, afterCompositedCropSha256: afterSource });
    const panBox = await canvas.boundingBox();
    await page.mouse.move(panBox.x + panBox.width * 0.5, panBox.y + panBox.height * 0.5);
    await page.mouse.down({ button: 'middle' });
    await page.mouse.move(panBox.x + panBox.width * 0.5 + 35, panBox.y + panBox.height * 0.5 + 20, { steps: 5 });
    await page.mouse.up({ button: 'middle' });
    await page.waitForTimeout(200);
    await page.screenshot({ path: resolve(output, `${viewport.name}-pan-after.png`), fullPage: true });
    result.steps.push({ name: 'actual-middle-pointer-pan', sourceGeometry: await sourceGeometry(), canvasPixelsChanged: afterCanvas !== await canvas.evaluate(node => node.toDataURL()), mobileInputNote: viewport.name === 'mobile' ? 'Mobile viewport with mouse emulation; not touch-pan proof.' : null });
    results.push(result);
    await context.close();
  }
} finally {
  await writeFile(resolve(proof, built ? 'built-ui-baseline.json' : 'ui-baseline.json'), JSON.stringify({ capturedAt: new Date().toISOString(), built, exactBuiltBytesServed: built, injection: false, browser: 'installed Playwright fallback; browser tool unavailable and agent-browser absent', results }, null, 2));
  await browser.close();
}
console.log(JSON.stringify(results, null, 2));
